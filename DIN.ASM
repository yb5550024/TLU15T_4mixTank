EXTRN  __RETNI:FAR
EXTRN  __PARNI:FAR

DGROUP	GROUP	DATASG
DATASG	SEGMENT  PUBLIC '_DATA'
M2    db     ?
DATASG ENDS
PROG  SEGMENT  'CODE'
      ASSUME  CS:PROG,DS:DGROUP
dIN PROC  FAR
     PUSH  BP
     MOV  BP,SP
     push DS
     push ES
     push SI
     push DI
	  MOV AX,1
	  PUSH AX
	  CALL __PARNI
	  ADD SP,2
	  MOV SI,AX
	  MOV DX,226H
	  IN AX,DX
	  MOV BX,01H
	  TEST SI,0FFFFH
	  JZ   DOLP55
	  MOV CX,SI
DOLP5:	  ROL BX,1
	  LOOP DOLP5
 DOLP55:  AND AX,BX
	  TEST AX,0FFFFH
	  JZ	LL0
	  MOV AX,01H
	 JMP STOP
 LL0:	 MOV AX,0H

 STOP:	  PUSH AX
	  CALL	__RETNI
	  ADD SP,2

   POP DI
   POP SI
   POP ES
   POP DS
   POP BP

   RET
dIN  ENDP
PROG  ENDS
END

